ALTER TABLE usuarios ADD COLUMN telefono varchar(30);

-- Contacto (snapshot) en la cita
ALTER TABLE citas ADD COLUMN contacto_nombre   varchar(120);
ALTER TABLE citas ADD COLUMN contacto_apellido varchar(120);
ALTER TABLE citas ADD COLUMN contacto_correo   varchar(150);
ALTER TABLE citas ADD COLUMN contacto_telefono varchar(30);

-- Notificaciones in-app del cliente (R-14)
CREATE TABLE notificaciones (
    id         bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id bigint       NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    cita_id    bigint       REFERENCES citas (id) ON DELETE CASCADE,
    tipo       varchar(30)  NOT NULL,
    mensaje    varchar(300) NOT NULL,
    leida      boolean      NOT NULL DEFAULT false,
    fecha      timestamptz  NOT NULL DEFAULT now()
);

CREATE INDEX idx_notificaciones_usuario ON notificaciones (usuario_id, leida);
CREATE INDEX idx_notificaciones_cita ON notificaciones (cita_id);
