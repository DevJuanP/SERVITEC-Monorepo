CREATE TABLE tipos_cita (
    id     bigint      PRIMARY KEY,
    nombre varchar(30) NOT NULL UNIQUE
);

CREATE TABLE citas (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id     bigint      NOT NULL REFERENCES usuarios (id),
    asesor_id      bigint      NOT NULL REFERENCES usuarios (id),
    tipo_cita_id   bigint      NOT NULL REFERENCES tipos_cita (id),
    estado         varchar(20) NOT NULL DEFAULT 'Pendiente'
                   CHECK (estado IN ('Pendiente', 'Aprobada', 'Realizada', 'Cancelada')),
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    fecha_cita     timestamptz NOT NULL,
    descripcion    text,
    observacion    text
);

CREATE INDEX idx_citas_cliente ON citas (cliente_id);
CREATE INDEX idx_citas_asesor ON citas (asesor_id);
CREATE INDEX idx_citas_fecha ON citas (fecha_cita);

CREATE UNIQUE INDEX uq_citas_agenda
    ON citas (asesor_id, fecha_cita)
    WHERE estado <> 'Cancelada';
