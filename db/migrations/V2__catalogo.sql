CREATE TABLE categorias (
    id   bigint      PRIMARY KEY,
    name varchar(60) NOT NULL UNIQUE
);

CREATE TABLE subcategorias (
    id           bigint      PRIMARY KEY,
    name         varchar(60) NOT NULL,
    categoria_id bigint      NOT NULL REFERENCES categorias (id),
    CONSTRAINT uq_subcategorias_categoria_name UNIQUE (categoria_id, name)
);

CREATE TABLE productos (
    id              bigint         PRIMARY KEY,
    name            varchar(150)   NOT NULL,
    price           numeric(10, 2) NOT NULL CHECK (price > 0),
    stock           int            NOT NULL DEFAULT 0 CHECK (stock >= 0),
    img             varchar(500),
    subcategoria_id bigint         NOT NULL REFERENCES subcategorias (id)
);

CREATE TABLE caracteristicas (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id bigint       NOT NULL REFERENCES productos (id) ON DELETE CASCADE,
    descripcion varchar(300) NOT NULL,
    orden       int          NOT NULL DEFAULT 0,
    CONSTRAINT uq_caracteristicas_producto_orden UNIQUE (producto_id, orden)
);

CREATE INDEX idx_subcategorias_categoria ON subcategorias (categoria_id);
CREATE INDEX idx_productos_subcategoria ON productos (subcategoria_id);
